test('the mod section carries the ask tool in hub mode only, and names its checks by the toggles (no hand, no codes)', () => {
  const hub = buildModSection(modCases['queue-hub']);
  assert.ok(hub.includes('registers through the `ask` tool'));
  /* every surface writes the whole question; on the desktop the mod hides it under the card */
  const side = (s) => buildSurfaceSection(modCases['queue-hub'], s, true);
  assert.ok(hub.includes('under the reply that asked') && !hub.includes('the decision table'));
  assert.ok(side('desktop').includes('the mod hides it under the card') && side('desktop').includes('the decision table'));
  assert.ok(side('terminal').includes('the mod hides nothing'));
  /* a handoff close hands the user the resume command alone in a copy block, and a close without it is flagged */
  assert.ok(hub.includes('`/askerdo resume TR-n` alone in a fenced copy block') && hub.includes("without the resume command's copy block"));
  assert.ok(hub.includes('writes no names line and no remark that none are open'));
  /* the app hides the band whenever the next-step box has height */
  assert.ok(hub.includes('next-step box carries the recap alone, never a question or a button'));
  /* the reply after a delivery opens with a receipt line, in hub mode only */
  assert.ok(hub.includes('receipt line naming each') && !buildModSection(modCases.defaults).includes('receipt line'));
  assert.ok(hub.includes('at 30 percent') && hub.includes('at 40 percent'));
  assert.ok(hub.includes('`/askerdo handoff`') && hub.includes('the shelf'));
  assert.ok(hub.includes('em and en dashes') && hub.includes('a footer state that disagrees with line 1'));
  assert.ok(!hub.includes('a raised hand with nothing owed') && !hub.includes('bare IDs'));
  assert.ok(!buildModSection(modCases.defaults).includes('`ask` tool'));
  const off = buildModSection(modCases['ids-off']);
  assert.ok(!off.includes('em and en dashes'));
  const plain = buildModSection(modCases['forecast-off']);
  assert.ok(!plain.includes('a footer state') && !plain.includes('\u{1F64B}'));
  for (const cfg of Object.values(modCases)) assert.doesNotMatch(buildModSection(cfg), /[\u2013\u2014]/);
});

