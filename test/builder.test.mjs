test('docsPath override rewrites both capability-doc references; the per-surface sections carry the rules', () => {
  const c = buildOutputStyle({ ...base, docsPath: '/plug/docs/' });
  assert.ok(c.includes('`/plug/docs/desktop-capabilities.md`'));
  assert.ok(c.includes('`/plug/docs/tui-capabilities.md`'));
  /* the docs are evidence, never reading; both sections ride whole, desktop first */
  const bare = { ...base, docs: false };
  assert.ok(!buildOutputStyle(bare).includes('capabilities.md'));
  for (const [s, cfg] of [[c, base], [buildOutputStyle(bare), bare]]) {
    assert.doesNotMatch(s, /read `[^`]*tui-capabilities\.md`/);
    const d = s.indexOf(buildSurfaceSection(cfg, 'desktop')), t = s.indexOf(buildSurfaceSection(cfg, 'terminal'));
    assert.ok(d > 0 && t > d);
  }
  assert.ok(c.includes('`/plug/docs/question-file.md`'));
  assert.ok(!c.includes('`docs/desktop-capabilities.md`'));
  const h = buildOutputStyle({ ...base, queue: 'hub', docsPath: '/plug/docs/' });
  assert.ok(h.includes('`/plug/docs/question-hub.md`'));
  assert.ok(h.includes('`/plug/docs/work-system.md`'));
  assert.ok(!h.includes('`docs/work-system.md`'));
});

test('the queue mode swaps footer machinery whole', () => {
  const text = buildOutputStyle(base);
  assert.ok(text.includes('The question queue.'));
  assert.ok(text.includes('Answering is typed'));
  assert.ok(text.includes('told in full exactly once'));
  assert.ok(text.includes('|questions|❓|'));
  assert.ok(!text.includes('complete set of what is outstanding'));
  assert.ok(!text.includes('work-system.md'), 'the work system rides hub mode only');
  assert.ok(!text.includes('the board never guesses'), 'so does the status ladder');
  assert.ok(!text.includes('waiting count'));
  const hub = buildOutputStyle({ ...base, queue: 'hub' });
  assert.ok(hub.includes('The question queue.'));
  assert.ok(hub.includes('the AskerDo hub'));
  assert.ok(hub.includes('question-hub.md'));
  assert.ok(hub.includes('`node ~/.claude/askerdo/cli.mjs register`'));
  /* where the mod runs the band carries the queue, so only a session without it ends on the names line */
  const queue = hub.slice(hub.indexOf('The question queue.'));
  const lead = queue.slice(0, queue.indexOf('end the reply with the names line'));
  assert.match(lead, /mod runs[^.]*no names line/);
  assert.match(lead, /without the mod/);
  /* one minimal pointer to the work system, read at its first touch */
  assert.ok(hub.includes('work-system.md'));
  assert.equal((hub.match(/work-system\.md/g) || []).length, 1);
  /* the status ladder, in one clause, so a session that never opens the doc
   * still knows when a task flips */
  assert.ok(hub.includes('A task this session or its agents are working on '
    + 'reads `in_progress` from the first dispatch and `completed` when the '
    + 'work lands where its Intent says: a session flips it, the board never '
    + 'guesses.'));
  assert.ok(hub.includes('|questions|❓|'));
  assert.ok(!hub.includes('question-file.md'));
  assert.ok(!hub.includes('.claude/questions/'));
  assert.ok(!hub.includes('Answering is typed'));
  assert.ok(hub.includes('surface <id> --session <own-id>'));
  assert.ok(hub.includes('re-check the board between work items'));
  assert.ok(hub.includes('may Monitor the board and resume the moment it lands, never uninvited'));
  /* a settled decision lives in the board's decision record, never Claude memory */
  const durable = hub.match(/[^.]*durable project decision[^.]*\./)[0];
  assert.ok(durable.includes('decision record') && durable.includes('`decide`'));
  assert.ok(!durable.includes('note or memory'));
  /* the typed q output carries ONE trailing line for what is asleep and what each
     sleeper waits on, read from the list verb the rule already names, and nothing at
     all when nothing is asleep */
  assert.ok(hub.includes('Typing "q" prints the open set as typed decision tables plus the '
    + 'board link, then one trailing line for what is asleep, read from '
    + '`list --project <projectDir> --snoozed --json`: each snoozed question and what it '
    + 'waits on (a date, a trigger, or the record a linked wake names), and nothing at all '
    + 'when none is asleep.'));
  /* the session-local FILE queue has no snooze at all, so its own q sentence
     is untouched and grows no such line */
  assert.ok(text.includes('typing "q" prints the open set as decision tables'));
  assert.ok(!text.includes('what is asleep'));
  assert.ok(hub.includes('told in full exactly once'));
  assert.ok(!hub.includes('complete set of what is outstanding'));
  assert.ok(!hub.includes('waiting count'));
  const off = buildOutputStyle({ ...base, queue: 'off' });
  assert.ok(!off.includes('The question queue.'));
  assert.ok(!off.includes('work-system.md'));
  assert.ok(!off.includes('the board never guesses'));
  assert.ok(!off.includes('|questions|'));
  assert.ok(off.includes('complete set of what is outstanding'));
  const plain = buildOutputStyle({ ...base, forecast: false });
  assert.ok(plain.includes('the question queue (next rule)'));
  assert.ok(plain.includes('The question queue.'));
  for (const s of [text, hub, off]) assert.ok(!s.includes('The bar is a widget'));
});

