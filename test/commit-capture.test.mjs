/* Commit capture, the PC half of review coverage: which task a commit
 * links to, and which of its files count as source. */
import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { tempDir } from './helpers/sandbox.mjs';
import { captureCommit, headsOf, linkCommit, linkPlan } from '../lib/commit-capture.mjs';

const git = async (dir, args) => {
  try { return { status: 0, out: execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }) }; }
  catch (e) { return { status: typeof e.status === 'number' ? e.status : -1, out: String(e.stdout || '') }; }
};
/* a board that knows T-1 to T-5 and refuses the rest as the verb does */
const board = () => {
  const sent = [];
  const send = async (p) => { sent.push(p); return /^T-[1-5]$/.test(p.task) || p.via === 'none' ? { ok: true } : { ok: false, error: 'no such task ' + p.task }; };
  return { sent, send };
};
const pick = async (o) => { const b = board(); return linkCommit(b.send, linkPlan(o), { sha: 'x' }); };

test('the task pick: a message id beats the agent, the agent beats the hand, two held guess the newest, an unknown id falls through', async () => {
  const hand = [{ id: 'T-3', since: '2026-11-01T09:00:00Z' }, { id: 'T-4', since: '2026-11-02T09:00:00Z' }];
  assert.deepEqual(await pick({ message: 'T-1, T-2: fix\n\nT-5 in the body', agentTasks: ['T-3'], hand }), { linked: ['T-1', 'T-2'], via: 'message' });
  assert.deepEqual(await pick({ message: 'T-99: a typo', agentTasks: ['T-3'], hand }), { linked: ['T-3'], via: 'agent' });
  assert.deepEqual(await pick({ message: 'fix', hand: hand.slice(0, 1) }), { linked: ['T-3'], via: 'in-hand' });
  assert.deepEqual(await pick({ message: 'fix', hand }), { linked: ['T-4'], via: 'guess' });
  assert.deepEqual(await pick({ message: 'fix' }), { linked: [], via: 'none' });
});

test('what counts: a lockfile, a doc, a fixture and a linguist-generated file do not; source and a test file do', async () => {
  const dir = tempDir('askerdo-commits-');
  const g = (...a) => execFileSync('git', ['-C', dir, ...a], { encoding: 'utf8' }).trim();
  g('init', '-q', '-b', 'main');
  g('config', 'user.email', 't@example.com');
  g('config', 'user.name', 't');
  g('config', 'commit.gpgsign', 'false');
  const put = (p, t) => { mkdirSync(dirname(join(dir, p)), { recursive: true }); writeFileSync(join(dir, p), t); };
  put('.gitattributes', 'gen/** linguist-generated\n');
  g('add', '.');
  g('commit', '-q', '-m', 'start');
  put('src/a.js', 'one\ntwo\n');
  put('test/a.test.mjs', 'three\n');
  put('package-lock.json', '{}\n');
  put('README.md', 'words\n');
  put('test/fixtures/case.json', '{}\n');
  put('gen/table.js', 'x\n');
  put('src/made.js', '// @generated by a tool\nx\n');
  g('add', '.');
  g('commit', '-q', '-m', 'T-2: the work');
  const b = board();
  const r = await captureCommit(git, b.send, { dirs: [dir], session: 's1' });
  assert.deepEqual(r.linked, ['T-2']);
  const p = b.sent[0];
  assert.deepEqual(p.files.filter((f) => f.counted).map((f) => f.path).sort(), ['src/a.js', 'test/a.test.mjs']);
  assert.equal(p.files.length, 7);
  assert.deepEqual([p.added, p.removed], [3, 0]);
  assert.match(p.sha, /^[0-9a-f]{40}$/);
  /* a commit call that started on this HEAD (a failed commit) links nothing again */
  const was = await headsOf(git, [dir]);
  assert.equal(await captureCommit(git, b.send, { dirs: [dir], was }), null);
  assert.equal(b.sent.length, 1);
  /* an amend keeps the author date, so the committer date is the one sent */
  execFileSync('git', ['-C', dir, 'commit', '-q', '--amend', '--no-edit'], { env: { ...process.env, GIT_COMMITTER_DATE: '2030-01-02T03:04:05Z' } });
  assert.deepEqual((await captureCommit(git, b.send, { dirs: [dir], was })).linked, ['T-2']);
  assert.match(b.sent[1].at, /^2030-01-02/);
});
