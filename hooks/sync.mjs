#!/usr/bin/env node
/* The output style is plugin-owned and regenerable, so it is rewritten whole
 * whenever it differs and no backup is kept. A SessionStart hook must never
 * break session start, so every error logs and the exit stays 0. */
import { readFileSync, writeFileSync, existsSync, mkdirSync, appendFileSync, statSync, readdirSync, cpSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildOutputStyle, buildChatPreferences, STYLE_NAME } from '../lib/builder.js';
import {
  MOVED_FILE, pluginRoot, pluginVersion, claudeHome, dataDir, envSeam, liveSeam, loadConfig, oldDirEdits, pcDir, pluginDataDir, replacedCopy, sandboxHome, storeRoot,
} from '../lib/node-helpers.mjs';
import { appendLog, writeAtomic } from '../lib/store-io.mjs';

const PREFS = 'claude-chat-preferences.md';
const COMMAND_MARK = '<!-- Generated by the AskerDo sync';
const args = new Set(process.argv.slice(2));

/* with ASKERDO_ROOT or ASKERDO_SANDBOX_HOME set, every write below lands under
 * the sandbox home (node-helpers sandboxHome), and an unusable seam writes nothing. */
const sandbox = sandboxHome();

/* resolved per call: the tests point HOME and USERPROFILE at a sandbox */
const claudeDir = () => claudeHome();
const stylePath = () => join(claudeDir(), 'output-styles', STYLE_NAME + '.md');
const settingsPath = () => join(claudeDir(), 'settings.json');

/* Never creates the dir: a log line about nothing would seed a stray data dir
 * in every context the harness names differently. */
function log(msg) {
  try {
    const dir = dataDir();
    if (!existsSync(dir)) return;
    appendFileSync(join(dir, 'sync.log'), new Date().toISOString() + ' ' + msg + '\n');
  } catch {}
}

/* The harness spawns 3 to 4 SessionStart hooks per event (observed), so
 * advisory output debounces on a stamp any flagless run touches. Real writes
 * are never gated by it. */
function recentSync() {
  try {
    const p = join(dataDir(), 'last-sync');
    const fresh = existsSync(p) && Date.now() - statSync(p).mtimeMs < 20000;
    writeFileSync(p, '');
    return fresh;
  } catch {
    return false;
  }
}

/* this PC's files leave the plugin data dir, which a marketplace remove deletes.
   The old dir stays as it was, so a downgrade still finds it; config.json goes last,
   so a copy that failed part way leaves the old dir in force and the next start retries. */
function moveDataDir() {
  const pc = pcDir();
  const old = pluginDataDir();
  if (!pc || !old) return;
  const file = join(pc, 'config.json');
  if (existsSync(file)) return foldOldEdits(file);
  try {
    mkdirSync(pc, { recursive: true });
    for (const n of readdirSync(old).filter((n) => n !== 'config.json')) {
      cpSync(join(old, n), join(pc, n), { recursive: true, force: true, preserveTimestamps: true });
    }
    const text = readFileSync(join(old, 'config.json'), 'utf8');
    writeAtomic(join(pc, MOVED_FILE), JSON.stringify({ from: old, base: JSON.parse(text) }, null, 2) + '\n', 0o600);
    /* renamed into place, so a sync starting beside this one never reads half a
       config; the harness starts several at once, and one another moved is never overwritten */
    if (!existsSync(file)) writeAtomic(file, text, 0o600);
    log("moved this PC's files from " + old + ' to ' + pc + ', where a plugin remove cannot reach them');
  } catch (e) {
    log("moving this PC's files to " + pc + ' failed, so ' + old + ' stays in use: ' + ((e && e.message) || e));
  }
}

/* a session still on a copy from before the move saves settings and joins into
   the old dir; the keys it changed there since the move are taken into pc/. */
function foldOldEdits(file) {
  const e = oldDirEdits();
  if (!e) return;
  try {
    const saved = JSON.parse(readFileSync(file, 'utf8'));
    for (const k of e.keys) saved[k] = e.now[k];
    writeAtomic(file, JSON.stringify(saved, null, 2) + '\n', 0o600);
    writeAtomic(join(dirname(file), MOVED_FILE), JSON.stringify({ from: e.from, base: e.now }, null, 2) + '\n', 0o600);
    log('took ' + e.keys.join(', ') + ' from ' + e.from + ', saved there by a session on an older AskerDo after the move');
  } catch (err) {
    log('taking the settings an older session saved in ' + e.from + ' failed: ' + ((err && err.message) || err));
  }
}

/* main()'s advisory debounce verdict, so the live-seam line prints once per burst */
let advisoryQuiet = false;
/* the board pull's wait at session start, and whether it ran out (declared up here:
   the body below runs before the functions' own lines are reached) */
const PULL_MS = 3000;
let pullHung = false;

if (sandbox && sandbox.problem) {
  process.stdout.write('AskerDo: sandbox seam refused: ' + sandbox.problem + '; nothing was written.\n');
} else if (replacedCopy()) {
  /* a session that outlived an update would put the old style, launcher and board
     back over the installed copy's at its next /clear */
  if (!recentSync()) {
    let v = 'unknown';
    try { v = pluginVersion(); } catch {}
    process.stdout.write('AskerDo: this session runs version ' + v + ', which a plugin update replaced, so nothing was synced; a new session runs the installed version.\n');
  }
} else {
  moveDataDir();
  /* a sandbox's own data dir is made up front, so its log and stamps have a home */
  if (sandbox) { try { mkdirSync(dataDir(), { recursive: true }); } catch {} }
  try {
    await main();
  } catch (e) {
    log('ERROR ' + ((e && e.stack) || e));
  }
  /* a seam naming the live store is no sandbox, said once per burst */
  const live = liveSeam();
  if (live) {
    log('ASKERDO_ROOT names the live store (' + live + '); not a sandbox, so the live files were synced');
    if (!advisoryQuiet) process.stdout.write('AskerDo: ASKERDO_ROOT names the live store (' + live + '), so this session is not a sandbox; the live output style and launcher were synced as usual.\n');
  }
  if (!args.has('--chat-prefs')) await hubMain();
  /* a pull that outlived its wait holds a socket open; the sync is done */
  if (pullHung) process.exit(0);
}

async function main() {
  const cfg = await pulled(loadConfig());
  if (!cfg) {
    // Unconfigured: touch nothing, but tell the session, since hook stdout
    // lands in model context. No log() either: an unconfigured run that left a
    // trace would seed an empty data dir per context.
    process.stdout.write('AskerDo: installed but not configured. Offer /askerdo:configure when convenient.\n');
    return;
  }
  const prefsPath = join(dataDir(), PREFS);
  const prefsNow = buildChatPreferences(cfg) + '\n';

  if (args.has('--chat-prefs')) {
    mkdirSync(dataDir(), { recursive: true });
    writeFileSync(prefsPath, prefsNow);
    process.stdout.write(prefsNow);
    log('chat preferences exported');
    return;
  }

  // Advisory output prints once per burst of duplicate hook spawns; --install
  // is an explicit action and never debounced.
  const quiet = !args.has('--install') && recentSync();
  advisoryQuiet = quiet;

  // Staleness nudge: the exported copy is what the user last pasted into
  // claude.ai; never overwrite it here, only compare.
  if (!quiet && existsSync(prefsPath) && readFileSync(prefsPath, 'utf8') !== prefsNow) {
    process.stdout.write('AskerDo: your claude.ai chat preferences copy is stale; run /askerdo:chat-preferences and paste the new text.\n');
    log('chat preferences stale');
  }

  const version = pluginVersion();
  const o = { ...cfg, rev: version, docsPath: join(pluginRoot, 'docs').replace(/\\/g, '/') + '/' };
  /* on a sandbox store the contract names that store's launcher, which hubMain keeps */
  if (sandbox && sandbox.home) {
    const cli = join(storeRoot(), 'cli.mjs').replace(/\\/g, '/');
    o.launcher = 'node ' + (/\s/.test(cli) ? '"' + cli + '"' : cli);
  }
  writeStyle(buildOutputStyle(o), version);
  await writeCommand();
  await keepPluginUpdates(cfg);
  if (args.has('--install')) selectStyle();
  /* a sandbox home has no settings of its own, so the nag would always be false there */
  else if (!quiet && !(sandbox && sandbox.home)) warnUnselected();
}

/* a board user's options live on their profile; this PC's config.json is
   the copy, refreshed here through the local server's cache, so an offline start
   builds from the last one. --no-pull follows a save that wrote both (settings set). */
async function pulled(cfg) {
  if (!cfg || !cfg.boardToken || args.has('--no-pull')) return cfg;
  try {
    const file = join(dataDir(), 'config.json');
    if (!existsSync(file)) return cfg;
    const { boardCall, boardUrl, localRoute } = await import('../lib/board-call.mjs');
    const url = boardUrl();
    /* the board itself only through this PC's local server, never a direct call at session start */
    if (/^https?:/i.test(url) && !localRoute(url)) return cfg;
    const { contractOf } = await import('../server/verbs/profile-rules.mjs');
    let timer;
    const late = new Promise((ok) => { timer = setTimeout(() => { pullHung = true; ok(null); }, PULL_MS); });
    const list = await Promise.race([boardCall('profileList', {}), late]).finally(() => clearTimeout(timer));
    if (!list) { log("options pull: no answer in " + PULL_MS / 1000 + " s; built from this PC's copy"); return cfg; }
    const { profile, values } = contractOf(list);
    if (!Object.keys(values).length) return cfg;
    const saved = JSON.parse(readFileSync(file, 'utf8'));
    if (Object.keys(values).some((k) => JSON.stringify(saved[k]) !== JSON.stringify(values[k]))) {
      writeAtomic(file, JSON.stringify({ ...saved, ...values }, null, 2) + '\n', 0o600);
      log('options pulled from the board profile ' + profile);
    }
    return { ...cfg, ...values };
  } catch (e) {
    log("options pull failed, built from this PC's copy: " + ((e && e.message) || e));
    return cfg;
  }
}

function read(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
}

/* Pure content compare: whatever
   the generator produces wins over whatever sits on disk. */
function writeStyle(content, version) {
  const p = stylePath();
  const current = read(p);
  /* nothing changed, so nothing prints and nothing logs */
  if (current === content) return;
  mkdirSync(join(claudeDir(), 'output-styles'), { recursive: true });
  writeFileSync(p, content);
  process.stdout.write('AskerDo: output style regenerated at rev ' + version + '. It takes effect in the next session or after /clear.\n');
  log((current ? 'rewrote' : 'created') + ' output style rev ' + version);
}

/* the app checks its command list before the mod registers /askerdo, so a
   user command file lists it from a session's start. The mod answers it with no
   model turn; a hand-made file of the name, without the mark, is never touched. */
async function writeCommand() {
  try {
    const { COMMAND, COMMAND_DESCRIPTION, COMMAND_HINT } = await import('../lib/mod-core.mjs');
    const p = join(claudeDir(), 'commands', COMMAND + '.md');
    const content = '---\ndescription: ' + JSON.stringify(COMMAND_DESCRIPTION) + '\nargument-hint: ' + JSON.stringify(COMMAND_HINT) + '\n---\n\n'
      + COMMAND_MARK + ', which keeps this file current; without this line it is left alone. -->\n\n'
      + '/' + COMMAND + ' is answered by the AskerDo mod without a model turn, so reading this text means the mod did not run this line as its command: '
      + 'the line came inside other text (a started session\'s brief, a pasted message), or the mod is not loaded in this session. '
      + 'With the AskerDo tools present (handoff_write, ask), the mod is loaded: do the line\'s work yourself. For /' + COMMAND + ' resume TR-n, run '
      + 'node ' + join(pluginRoot, 'bin', 'askerdo.mjs').replace(/\\/g, '/') + ' resume TR-n --session <your session id, the CLAUDE_CODE_SESSION_ID of your shell> '
      + 'and read the kickoff it prints. Only with no AskerDo tools, tell the user that /' + COMMAND + ' did not run because the AskerDo mod is not loaded in this session, and do nothing else.\n';
    const current = existsSync(p) ? read(p) : null;
    if (current === content || (current !== null && !current.includes(COMMAND_MARK))) return;
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
    log((current === null ? 'created' : 'rewrote') + ' the /' + COMMAND + ' command file ' + p);
  } catch (e) {
    log('ERROR command file ' + ((e && e.message) || e));
  }
}

/* a marketplace remove and add drops the app's autoUpdate key (measured
   2026-11-04, claude 2.1.304), so a missing key gets the saved answer back; a value the app
   holds is the person's own /plugin choice and becomes the saved one. Fail-open, one log line. */
async function keepPluginUpdates(cfg) {
  const saved = cfg.pluginUpdates;
  if (saved !== 'on' && saved !== 'off') return;
  try {
    const { pluginUpdates, setPluginUpdates } = await import('../lib/plugin-updates.mjs');
    const now = pluginUpdates();
    if (now.on === null || now.on === (saved === 'on')) return;
    if (now.set) {
      const to = now.on ? 'on' : 'off';
      const why = adoptUpdates(to);
      log(why ? "the app's auto-update for " + now.name + ' is ' + to + ' and the saved ' + saved + ' could not follow it: ' + why
        : "the app's auto-update for " + now.name + ' was turned ' + to + ' in the app, so pluginUpdates is saved as ' + to);
      return;
    }
    const r = setPluginUpdates(saved === 'on');
    log(r.ok ? "the app's auto-update for " + r.name + ' was unset, set back to the saved ' + saved
      : "setting the app's auto-update back to " + saved + ' failed: ' + r.why);
  } catch (e) {
    log("setting the app's auto-update back to " + saved + ' failed: ' + ((e && e.message) || e));
  }
}

/* The app's value into this PC's own config.json, every other key kept; the reason it was
   not written, or '' (a sandbox reading the real config has no file of its own to change). */
function adoptUpdates(to) {
  const dir = dataDir();
  if (!dir) return 'no data folder';
  const file = join(dir, 'config.json');
  let saved;
  try { saved = JSON.parse(readFileSync(file, 'utf8').replace(/^\uFEFF/, '')); } catch (e) { return (e && e.message) || String(e); }
  if (!saved || typeof saved !== 'object' || Array.isArray(saved)) return file + ' is not a JSON object';
  if (saved.pluginUpdates === undefined) return file + ' holds no pluginUpdates';
  writeAtomic(file, JSON.stringify({ ...saved, pluginUpdates: to }, null, 2) + '\n', 0o600);
  return '';
}

/* --install only. Merges one key and leaves every other setting, including
   key order, exactly as parsed; refuses to write over a file it cannot parse. */
function selectStyle() {
  const p = settingsPath();
  const raw = read(p);
  let obj = {};
  if (raw.trim()) {
    try {
      obj = JSON.parse(raw);
    } catch {
      obj = null;
    }
    if (!obj || typeof obj !== 'object' || Array.isArray(obj)) {
      process.stdout.write('AskerDo: ~/.claude/settings.json is not a JSON object, so it was left untouched. Add "outputStyle": "' + STYLE_NAME + '" to it by hand.\n');
      log('settings.json unreadable as an object; outputStyle not set');
      return;
    }
  }
  if (obj.outputStyle === STYLE_NAME) return;
  // Only on a real change, so this stays a one-time copy in practice, and
  // through backup_ so an unrelated settings.json.bak is never clobbered.
  const previous = obj.outputStyle;
  const bak = backup_(p, raw);
  obj.outputStyle = STYLE_NAME;
  mkdirSync(claudeDir(), { recursive: true });
  writeFileSync(p, JSON.stringify(obj, null, 2) + '\n');
  process.stdout.write('AskerDo: selected the "' + STYLE_NAME + '" output style in ~/.claude/settings.json'
    + (previous ? ' (was "' + previous + '")' : '') + (bak ? '; the file as it was is in ' + basename(bak) : '')
    + '. It takes effect in the next session or after /clear.\n');
  log('outputStyle set to ' + STYLE_NAME + (previous ? ' (was ' + previous + ')' : ''));
}

/* Hook mode never edits settings.json, so a style that nothing selects is a
   silent no-op. Say so instead. */
function warnUnselected() {
  let current;
  try {
    const parsed = JSON.parse(read(settingsPath()) || '{}');
    if (parsed && typeof parsed === 'object') current = parsed.outputStyle;
  } catch {}
  if (current === STYLE_NAME) return;
  process.stdout.write('AskerDo: the output style is installed but ~/.claude/settings.json does not select it'
    + (current ? ' (outputStyle is "' + current + '")' : ' (no outputStyle set)')
    + '. Run /askerdo:configure to set it.\n');
  log('outputStyle not selected (' + (current === undefined ? 'unset' : current) + ')');
}

function backup_(path, content) {
  if (!content) return '';
  let p = path + '.bak';
  let n = 1;
  while (existsSync(p)) p = path + '.bak' + n++;
  writeFileSync(p, content);
  return p;
}

/* The hub additions, gated on queue mode and inside one try/catch, so they can
 * never break the sync. The launcher write is the one place a hook creates the
 * root: hub mode is the opt-in, except a sandbox's, whose contract names it. */

async function hubMain() {
  let root;
  try {
    const cfg = loadConfig();
    if (!cfg) return;
    const own = Boolean(sandbox && sandbox.home);
    if (cfg.queue !== 'hub' && !own) return;
    root = storeRoot();
    refreshLauncher(root, own);
    if (cfg.queue !== 'hub') return;
    await learnProject();
    /* the ensure points the one machine-wide scheduled task, so a sandbox never runs it */
    if (sandbox) appendLog(root, 'board ensure skipped: sandbox seam (' + sandbox.from + ')');
    else await ensureBoard(root);
    /* the board this PC hosts gets its copy at the day's first session start */
    const { dailyBackup } = await import('../lib/board-backup.mjs');
    await dailyBackup(root, { cfg });
  } catch (e) {
    if (root) appendLog(root, 'sync hub additions failed: ' + ((e && e.stack) || e));
    log('ERROR hub ' + ((e && e.stack) || e));
  }
}

/* each session start maps its project's shared name to this PC's folder. */
async function learnProject() {
  try {
    const { learnProjects } = await import('../lib/project-map.mjs');
    const r = learnProjects(dataDir(), [process.env.CLAUDE_PROJECT_DIR || process.cwd()]);
    for (const a of r.added) log('project map: ' + a.name + ' is ' + a.dir);
  } catch (e) {
    log('ERROR project map ' + ((e && e.message) || e));
  }
}

/* Each plugin update lands in a new versioned cache path, so this two-line file
 * is what external callers can point at forever. Read-compare first, so a
 * current launcher never churns. */
function refreshLauncher(root, own = false) {
  const target = pathToFileURL(join(pluginRoot, 'bin', 'askerdo.mjs')).href;
  const content = '/* AskerDo launcher, maintained by the AskerDo sync; edits are overwritten */\n'
    + 'await import(' + JSON.stringify(target) + ');\n';
  const done = writeLauncher(root, content, own);
  if (done) log('AskerDo launcher ' + done);
}

/* the plugin root an AskerDo launcher imports, or null when the
 * file is not one this sync wrote. */
function launcherTarget(text) {
  const m = /^\/\* AskerDo launcher[^\n]*\*\/\nawait import\(("(?:[^"\\]|\\.)*")\);\n?$/.exec(text);
  if (!m) return null;
  try {
    const file = fileURLToPath(JSON.parse(m[1]));
    if (basename(file) !== 'askerdo.mjs' || basename(dirname(file)) !== 'bin') return null;
    return dirname(dirname(file));
  } catch {
    return null;
  }
}

/* function declarations, not consts: hubMain() runs before this point of the
   module body is evaluated */
function samePath(a, b) {
  const norm = (p) => resolve(p).replace(/[\\/]+$/, '');
  return process.platform === 'win32' ? norm(a).toLowerCase() === norm(b).toLowerCase() : norm(a) === norm(b);
}

function parseVersion(v) {
  return typeof v === 'string' && /^\d+(\.\d+)*$/.test(v) ? v.split('.').map(Number) : null;
}

/* x.y.z compared part by part; an unreadable side is never newer. */
function strictlyNewer(a, b) {
  const x = parseVersion(a);
  const y = parseVersion(b);
  if (!x || !y) return false;
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    const d = (x[i] || 0) - (y[i] || 0);
    if (d) return d > 0;
  }
  return false;
}

/* A launcher another live copy owns stays unless this copy is strictly newer; one
 * that is not ours, or whose copy is gone or unreadable, may be repointed. */
function launcherOwner(current) {
  const target = current === null ? null : launcherTarget(current);
  if (!target || samePath(target, pluginRoot)) return null;
  /* a copy Claude Code replaced (a rollback leaves the newer one) is dead too */
  if (!existsSync(join(target, 'bin', 'askerdo.mjs')) || replacedCopy(target)) return null;
  let theirs;
  try { theirs = JSON.parse(readFileSync(join(target, '.claude-plugin', 'plugin.json'), 'utf8')).version; } catch { return null; }
  if (!parseVersion(theirs)) return null;
  let ours = null;
  try { ours = pluginVersion(); } catch {}
  if (worktreeCopy()) return { target, theirs, ours, worktree: true };
  if (strictlyNewer(ours, theirs)) return null;
  return { target, theirs, ours };
}

/* A linked git worktree (its .git is a file) is a build copy, so a
 * release bump there never takes a launcher another live copy owns. ASKERDO_COPY_KIND
 * (worktree or checkout) is the test seam. */
function worktreeCopy() {
  const kind = envSeam('COPY_KIND');
  if (kind === 'worktree' || kind === 'checkout') return kind === 'worktree';
  try { return statSync(join(pluginRoot, '.git')).isFile(); } catch { return false; }
}

/* Returns what it did, for the one log line. A
 * sandbox's root is this copy's own, so no other copy's launcher outranks it. */
function writeLauncher(dir, content, own = false) {
  const p = join(dir, 'cli.mjs');
  let current = null;
  try { current = readFileSync(p, 'utf8'); } catch {}
  if (current === content) return '';
  const owner = own ? null : launcherOwner(current);
  if (owner) {
    log('launcher left at ' + dir + ': it points at version ' + owner.theirs + ' at ' + owner.target
      + (owner.worktree ? ', and this copy (' + (owner.ours || 'unreadable') + ') is a git worktree, which never takes it'
        : ', not older than this copy (' + (owner.ours || 'unreadable') + ')'));
    return '';
  }
  mkdirSync(dir, { recursive: true });
  writeAtomic(p, content);
  return (current === null ? 'written at ' : 're-pointed at ') + dir;
}

/* Ping-or-start so names-line links resolve from the first session;
 * the task starts it, so the board is never a child of the session.
 * NO_BOARD is a test seam. */
async function ensureBoard(root) {
  if (envSeam('NO_BOARD')) return;
  try {
    const { ensureBoardServer } = await import('../lib/board-ensure.mjs');
    const r = await ensureBoardServer(root);
    if (r.status !== 'running') appendLog(root, 'board ensure: ' + r.status + (r.detail ? ' (' + r.detail + ')' : ''));
  } catch (e) {
    appendLog(root, 'board ensure failed: ' + ((e && e.stack) || e));
    log('ERROR board ensure ' + ((e && e.message) || e));
  }
}
